const area = document.querySelector('#suspects');
const name = document.querySelector('#name');
const role = document.querySelector('#role');
const testimony = document.querySelector('#testimony');
const replay = document.querySelector('#replay');
let selected;
let typingTimer;

const access = document.querySelector('#case-access');
function showAccess() {
  access.innerHTML = `<div class="access-wrap"><article class="access-card" style="background-image:linear-gradient(to bottom,rgba(0,0,0,.02) 30%,rgba(0,0,0,.18) 52%,rgba(0,0,0,.96) 100%),url('../images/quarto307.png');background-size:cover;background-position:center"><div class="card-code">ARQ. 001</div><p>caso disponível agora</p><h2>O Quarto<br><em>307</em></h2><span class="card-arrow">↗</span></article><button class="access-open" type="button">ABRIR</button><div class="pin-area"><h2>Digite a senha</h2><p>Use o código de acesso do seu caso.</p><div class="pin-dots">○ ○ ○ ○</div><div class="keypad">${[1,2,3,4,5,6,7,8,9].map(number => `<button data-key="${number}">${number}</button>`).join('')}<button class="clear" data-key="clear">limpar</button><button data-key="0">0</button><button class="clear" data-key="back">←</button></div><div class="lock-error"></div></div></div>`;
  access.querySelector('.access-open').onclick = () => access.classList.add('show-pin');
  let pin = '';
  const dots = access.querySelector('.pin-dots');
  const error = access.querySelector('.lock-error');
  access.querySelectorAll('[data-key]').forEach(button => {
    button.onclick = () => {
      const key = button.dataset.key;
      pin = key === 'clear' ? '' : key === 'back' ? pin.slice(0, -1) : pin.length < 4 ? pin + key : pin;
      dots.textContent = [0, 1, 2, 3].map(index => index < pin.length ? '●' : '○').join(' ');
      if (pin.length !== 4) return;
      if (pin === '0307') {
        access.remove();
      } else {
        error.textContent = 'senha incorreta · acesso negado';
        pin = '';
        setTimeout(() => { dots.textContent = '○ ○ ○ ○'; }, 450);
      }
    };
  });
}
showAccess();

function typeText(text) {
  clearInterval(typingTimer);
  testimony.textContent = '';
  let position = 0;
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (reducedMotion) {
    testimony.textContent = text;
    return;
  }
  typingTimer = setInterval(() => {
    testimony.textContent += text[position++];
    if (position >= text.length) clearInterval(typingTimer);
  }, 24);
}

function showTestimony(person) {
  selected = person;
  name.textContent = person.nome;
  role.textContent = `${person.papel} · ${person.idade} anos`;
  typeText(person.depoimento || 'Este depoimento ainda está sendo preparado pelo investigador.');
}

Promise.all(people.map(([id, photo]) =>
  fetch(`../interrogatorio/suspeitos/${id}.json`)
    .then(response => {
      if (!response.ok) throw new Error('Arquivo não encontrado');
      return response.json();
    })
    .then(data => ({ ...data, depoimento: statements[data.id] || data.depoimento, photo }))
)).then(data => {
  area.innerHTML = '';
  data.forEach((person, index) => {
    const button = document.createElement('button');
    button.className = `suspect${index === 0 ? ' active' : ''}`;
    button.type = 'button';
    button.innerHTML = `<span class="suspect-no">${String(index + 1).padStart(2, '0')}</span><span class="portrait"><img src="../interrogatorio/images/${person.photo}" alt="Foto de ${person.nome}"><span class="portrait-initial">${person.nome[0]}</span></span><span><b>${person.nome}</b><small>${person.papel}</small></span><i>→</i>`;
    button.querySelector('img').onerror = event => event.currentTarget.remove();
    button.addEventListener('click', () => {
      area.querySelectorAll('.suspect').forEach(item => item.classList.remove('active'));
      button.classList.add('active');
      showTestimony(person);
      document.querySelector('.testimony-panel').scrollIntoView({ behavior: 'smooth', block: 'start' });
    });
    area.append(button);
  });
  showTestimony(data[0]);
}).catch(() => {
  name.textContent = 'Arquivo indisponível';
  testimony.textContent = 'Não foi possível carregar os depoimentos. Tente recarregar a página.';
});

replay.addEventListener('click', () => {
  if (selected) showTestimony(selected);
});
